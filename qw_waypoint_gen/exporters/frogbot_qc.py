"""
:File:      exporters/frogbot_qc.py

:Details:   Emits Frogbot map_<name>.qc waypoint files in the exact format the
            Frogbot waypoint tool dumps (manual.qc SaveMarkers), compatible with
            the mod compiler and waypoint_map_inject.py.

:Date:      2026-07-06
:Author:    Mick K
"""

from __future__ import annotations

from pathlib import Path

from qw_waypoint_gen.nav.markers import Marker

# Frogbot save masks (defs.qc).
SAVED_T = 1023
SAVED_DESCRIPTION = 4095

_N_PER_LINE = 4
_STATEMENTS_PER_LINE = 8
_PATHS_PER_LINE = 6


def quakecify_map_name(map_name: str) -> str:
    """Turn a map name into a valid QuakeC function suffix.

    Mirrors generate_maplist.py: "+" becomes "PLUS" and "-" becomes "DASH".

    Args:
        map_name: Raw map name (BSP file stem).

    Returns:
        str: QuakeC-safe function suffix.
    """
    return map_name.replace("+", "PLUS").replace("-", "DASH")


def render_frogbot_qc(map_name: str, markers: list[Marker]) -> str:
    """Render a complete Frogbot waypoint QC file.

    Layout follows the waypoint tool dump: header, custom_marker_start,
    N() lines (4 per line, custom markers only), LSQ(), then Z/G/T blocks
    (8 statements per line), P/D blocks (6 per line), closing brace, and the
    MarkerInfo trailer comment listing every marker.

    Args:
        map_name: Map name (lowercase BSP stem).
        markers: Final marker list in index order.

    Returns:
        str: The QC file contents (LF newlines).
    """
    ordered = sorted(markers, key=lambda m: m.index)
    customs = [m for m in ordered if m.is_custom]
    first_custom_index = len(ordered) - len(customs) + 1

    lines: list[str] = [
        f"// Auto-generated by qw-waypoint-gen for map '{map_name}'.",
        "// Review and refine with the Frogbot waypoint tool before shipping.",
        f"void() map_{quakecify_map_name(map_name)} =",
        "{",
        f"custom_marker_start={first_custom_index};",
    ]

    lines.extend(_n_lines(customs))
    lines.append("LSQ();")
    lines.extend(_pack(_zone_statements(ordered), _STATEMENTS_PER_LINE))
    lines.extend(_pack(_goal_statements(ordered), _STATEMENTS_PER_LINE))
    lines.extend(_pack(_type_statements(ordered), _STATEMENTS_PER_LINE))
    lines.extend(_pack(_path_statements(ordered), _PATHS_PER_LINE))
    lines.extend(_pack(_flag_statements(ordered), _PATHS_PER_LINE))
    lines.append("};")
    lines.append("/* MarkerInfo")
    lines.extend(_marker_info_lines(ordered))
    lines.append("*/")
    lines.append("")
    return "\n".join(lines) + "\n"


def write_frogbot_qc(path: str | Path, map_name: str, markers: list[Marker]) -> None:
    """Write the rendered QC file to disk with LF newlines.

    Args:
        path: Output file path.
        map_name: Map name (lowercase BSP stem).
        markers: Final marker list in index order.
    """
    out_path = Path(path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(render_frogbot_qc(map_name, markers), newline="\n")


def _rint(value: float) -> int:
    """Round to nearest integer, mirroring QuakeC rint (half away from zero)."""
    if value >= 0.0:
        return int(value + 0.5)
    return -int(-value + 0.5)


def _n_lines(customs: list[Marker]) -> list[str]:
    """Render N(x,y,z); statements, four per line, custom markers only."""
    statements = [f"N({_rint(m.info_pos.x)},{_rint(m.info_pos.y)},{_rint(m.info_pos.z)});" for m in customs]
    return _pack(statements, _N_PER_LINE)


def _zone_statements(markers: list[Marker]) -> list[str]:
    """Render zone assignments for markers with a nonzero zone."""
    return [f"Z{m.zone}(m{m.index});" for m in markers if m.zone > 0]


def _goal_statements(markers: list[Marker]) -> list[str]:
    """Render goal assignments for markers with a nonzero goal."""
    return [f"G{m.goal}(m{m.index});" for m in markers if m.goal > 0]


def _type_statements(markers: list[Marker]) -> list[str]:
    """Render marker type flags, masked to the saved bits."""
    out: list[str] = []
    for marker in markers:
        masked = marker.marker_type & SAVED_T
        if masked:
            out.append(f"m{marker.index}.T={masked};")
    return out


def _path_statements(markers: list[Marker]) -> list[str]:
    """Render P-slot assignments (m<i>.P<n>=m<j>;)."""
    out: list[str] = []
    for marker in markers:
        for slot, dst_index in enumerate(marker.paths):
            out.append(f"m{marker.index}.P{slot}=m{dst_index};")
    return out


def _flag_statements(markers: list[Marker]) -> list[str]:
    """Render D-slot flags for path slots that have nonzero saved flags."""
    out: list[str] = []
    for marker in markers:
        for slot in range(len(marker.paths)):
            flags = marker.path_flags.get(slot, 0) & SAVED_DESCRIPTION
            if flags:
                out.append(f"m{marker.index}.D{slot}={flags};")
    return out


def _marker_info_lines(markers: list[Marker]) -> list[str]:
    """Render the MarkerInfo trailer: one marker per line, rounded positions."""
    return [
        f"m{m.index} {m.classname} " f"{_rint(m.info_pos.x)} {_rint(m.info_pos.y)} {_rint(m.info_pos.z)};"
        for m in markers
    ]


def _pack(statements: list[str], per_line: int) -> list[str]:
    """Join statements into lines of at most per_line statements each."""
    return ["".join(statements[i : i + per_line]) for i in range(0, len(statements), per_line)]
