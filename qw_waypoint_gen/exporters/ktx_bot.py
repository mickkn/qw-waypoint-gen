"""
:File:      exporters/ktx_bot.py

:Details:   Emits KTX bot route files (bots/maps/<name>.bot) in the command
            format parsed by KTX 1.47 LoadBotRoutingFromFile() (marker_load.c).

            KTX creates every entity marker itself at map load (items, spawns,
            teleports, doors, triggers) in edict order, then appends one marker
            per CreateMarker line. All marker numbers in the file are 1-based
            and must therefore match the KTX runtime numbering, which the
            generator's entity marker numbering reproduces.

:Date:      2026-11-07
:Author:    Mick K
"""

from __future__ import annotations

from pathlib import Path

from qw_waypoint_gen.nav.markers import Marker

# Path flag bits and the letters DecodeMarkerPathFlagString() accepts.
_PATH_FLAG_LETTERS = (
    (1 << 1, "w"),  # WATERJUMP_
    (1 << 8, "6"),  # DM6_DOOR
    (1 << 9, "r"),  # ROCKET_JUMP
    (1 << 10, "j"),  # JUMP_LEDGE
    (1 << 11, "v"),  # VERTICAL_PLATFORM
)

# Marker flag bits and the letters DecodeMarkerFlagString() accepts.
_MARKER_FLAG_LETTERS = (
    (1, "u"),  # UNREACHABLE
    (8, "6"),  # MARKER_IS_DM6_DOOR
    (16, "b"),  # MARKER_BLOCKED_ON_STATE_TOP
    (64, "t"),  # MARKER_DOOR_TOUCHABLE
    (128, "e"),  # MARKER_ESCAPE_ROUTE
    (32, "f"),  # MARKER_FIRE_ON_MATCH_START
    (1024, "n"),  # MARKER_NOTOUCH
)


def encode_path_flags(flags: int) -> str:
    """Encode path flag bits as a KTX SetMarkerPathFlags letter string.

    Args:
        flags: Path flag bits (Frogbot D-field values).

    Returns:
        str: Letter string, empty when no KTX-supported bit is set.
    """
    return "".join(letter for bit, letter in _PATH_FLAG_LETTERS if flags & bit)


def encode_marker_flags(flags: int) -> str:
    """Encode marker flag bits as a KTX SetMarkerFlag letter string.

    Args:
        flags: Marker type bits (Frogbot T-field values).

    Returns:
        str: Letter string, empty when no KTX-supported bit is set.
    """
    return "".join(letter for bit, letter in _MARKER_FLAG_LETTERS if flags & bit)


def render_ktx_bot(map_name: str, markers: list[Marker]) -> str:
    """Render a complete KTX .bot route file.

    Layout follows the files KTX ships: a CreateMarker line per custom marker
    in index order, then per marker SetGoal, SetZone, and each SetMarkerPath
    immediately followed by its SetMarkerPathFlags, then SetMarkerFlag.

    Args:
        map_name: Map name (lowercase BSP stem).
        markers: Final marker list in index order.

    Returns:
        str: The .bot file contents (LF newlines).
    """
    ordered = sorted(markers, key=lambda m: m.index)
    lines: list[str] = [f"// Auto-generated by qw-waypoint-gen for {map_name}"]
    lines.extend(_create_marker_line(m) for m in ordered if m.is_custom)
    for marker in ordered:
        lines.extend(_marker_lines(marker))
    return "\n".join(lines) + "\n"


def write_ktx_bot(path: str | Path, map_name: str, markers: list[Marker]) -> None:
    """Write the rendered .bot file to disk with LF newlines.

    Args:
        path: Output file path.
        map_name: Map name (lowercase BSP stem).
        markers: Final marker list in index order.
    """
    out_path = Path(path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(render_ktx_bot(map_name, markers), newline="\n")


def _rint(value: float) -> int:
    """Round to nearest integer, half away from zero (KTX pr1_rint)."""
    if value >= 0.0:
        return int(value + 0.5)
    return -int(-value + 0.5)


def _create_marker_line(marker: Marker) -> str:
    """Render the CreateMarker line for one custom marker."""
    pos = marker.info_pos
    return f"CreateMarker {_rint(pos.x)} {_rint(pos.y)} {_rint(pos.z)}"


def _marker_lines(marker: Marker) -> list[str]:
    """Render goal, zone, path, and flag commands for one marker."""
    out: list[str] = []
    if marker.goal > 0:
        out.append(f"SetGoal {marker.index} {marker.goal}")
    if marker.zone > 0:
        out.append(f"SetZone {marker.index} {marker.zone}")
    for slot, dst_index in enumerate(marker.paths):
        out.append(f"SetMarkerPath {marker.index} {slot} {dst_index}")
        letters = encode_path_flags(marker.path_flags.get(slot, 0))
        if letters:
            out.append(f"SetMarkerPathFlags {marker.index} {slot} {letters}")
    marker_letters = encode_marker_flags(marker.marker_type)
    if marker_letters:
        out.append(f"SetMarkerFlag {marker.index} {marker_letters}")
    return out
